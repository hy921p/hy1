async function seed() {
  const [rows] = await pool.query('SELECT content FROM questions');
  const existing = new Set(rows.map(r => r.content));

  const fresh = realQuestions.filter(q => !existing.has(q[4]));
  if (!fresh.length) {
    console.log('[seed] 010 真实真题扩充已全部存在，跳过');
    return;
  }

  const conn = await pool.getConnection();
  try {
    await conn.beginTransaction();
    const sql =
      'INSERT INTO questions (content, detail, category, industry, position, region, source_type, year, ' +
      'type, difficulty, reference_answer, tags, usage_count, avg_score, status, created_by, deleted_at, operated_by) ' +
      'VALUES (?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?)';
    for (const [category, type, year, region, content, ref] of fresh) {
      await conn.query(sql, [
        content, null, category, '公共部门', '公务员', region, 'real', year,
        type, 1, ref, JSON.stringify(['真题']), 0, null, 1, 1, null, null,
      ]);
    }
    await conn.commit();
    console.log(`[seed] 010 已导入真实真题 ${fresh.length} 道（现有题库 ${existing.size} 道）`);
  } catch (e) {
    await conn.rollback();
    throw e;
  } finally {
    conn.release();
  }
}

